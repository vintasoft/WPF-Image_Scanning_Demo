namespace Vintasoft.UniversalImageScanner
{
    /// <summary>
    /// Specifies available image pixel types for image that is transferred from simple image scanner.
    /// </summary>
    public enum ImagePixelType
    {
        /// <summary>
        /// Black-white image.
        /// </summary>
        BlackWhite = 0,
        /// <summary>
        /// Grayscale image.
        /// </summary>
        Grayscale = 2,
        /// <summary>
        /// RGB image.
        /// </summary>
        RGB = 3,
    }
}
